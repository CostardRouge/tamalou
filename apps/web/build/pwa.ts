import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';
import { GENERATED } from './seo.ts';
import { OG_IMAGES, PLAY_PATH } from './site.ts';

const PLAY_PAGE = `${PLAY_PATH}index.html`;

/** Read by crawlers and unfurlers, never by a phone playing offline: robots.txt, the sitemap, llms.txt, the social cards. */
const NOT_OFFLINE = new Set<string>([...GENERATED, ...Object.values(OG_IMAGES).map((card) => card.path)]);

// The offline game (docs/SPEC.md §8, M8): after the build, a service worker is written at the site's root with the
// list of every file to keep and a version made from their contents. Solo and pass-and-play then work without a
// network; rooms never go through it (/api/ is left to the network). The game page (play/) registers it for the whole
// site, so the home pages open offline too (ADR-0017).

/** Files a phone needs offline: the page, scripts, styles, fonts, icons, manifest. */
export function precacheList(files: string[]): string[] {
  return files
    .filter((f) => f !== 'sw.js' && !NOT_OFFLINE.has(f) && !f.endsWith('.map') && !f.endsWith('.woff'))
    .sort((a, b) => (a === 'index.html' ? -1 : b === 'index.html' ? 1 : a.localeCompare(b)));
}

export function serviceWorkerSource(files: string[], version: string): string {
  return `// Generated by apps/web/build/pwa.ts at build time. Do not edit.
const VERSION = ${JSON.stringify(version)};
const FILES = ${JSON.stringify(files)};
const CACHE = 'tamalou-' + VERSION;
const scoped = (f) => new URL(f, self.registration.scope).href;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map(scoped))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('tamalou-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

/** The network, unless it takes longer than a phone on bad Wi-Fi should wait. */
const fresh = (request) =>
  Promise.race([fetch(request), new Promise((_, ko) => setTimeout(() => ko(new Error('slow')), 4000))]);

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.includes('/api/')) return;
  if (request.mode === 'navigate') {
    // The page from the network when it answers (a new version shows at once), else the cached one: the folder's
    // index.html, or the game for an address the site does not have.
    const scope = new URL(self.registration.scope).pathname;
    const rel = url.pathname.startsWith(scope) ? url.pathname.slice(scope.length) : '';
    const page = rel === '' || rel.endsWith('/') ? rel + 'index.html' : rel;
    event.respondWith(
      fresh(request).catch(() =>
        caches.match(scoped(page)).then((hit) => hit || caches.match(scoped(${JSON.stringify(PLAY_PAGE)}))),
      ),
    );
    return;
  }
  // Built files never change under the same name: the cache first.
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)));
});
`;
}

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  );
}

export function pwa(): Plugin {
  let outDir = 'dist';
  return {
    name: 'tamalou-pwa',
    apply: 'build',
    configResolved(config) {
      outDir = join(config.root, config.build.outDir);
    },
    closeBundle() {
      const files = precacheList(walk(outDir).map((f) => relative(outDir, f).split(sep).join('/')));
      const hash = createHash('sha256');
      for (const f of files) hash.update(f).update(readFileSync(join(outDir, f)));
      writeFileSync(join(outDir, 'sw.js'), serviceWorkerSource(files, hash.digest('hex').slice(0, 12)));
    },
  };
}
